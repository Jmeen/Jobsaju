/** 세트 번호를 그 세트의 여섯 마리로 바꾼다. */
export function teaseSet(setIndex: number): LandingTease[] {
  const set = LANDING_TEASE_SETS[setIndex] ?? LANDING_TEASE_SETS[0];
  return set.map(sequence => LANDING_TEASES[sequence - 1]);
}

const SET_STORAGE_KEY = 'jobsaju_landing_set_v1';

/**
 * 이번 방문에 세울 세트 번호. 읽기만 한다 — 다음 번호를 적는 일은 advanceTeaseSet이 한다.
 *
 * 읽기와 쓰기를 나눠 둔 이유가 있다. 한 함수로 묶어 두면 호출한 쪽에서 렌더 중에 부르게 되고,
 * React가 초기화 함수를 두 번 부르는 개발 모드에서는 세트가 두 칸씩 건너뛴다.
 *
 * 저장이 막힌 환경(시크릿 모드 등)에서는 무작위로 떨어뜨린다 — 매번 1번만 보는 것보다 낫다.
 */
export function currentTeaseSetIndex(
  storage: Storage | null = typeof localStorage === 'undefined' ? null : localStorage,
  random: () => number = Math.random,
): number {
  const total = LANDING_TEASE_SETS.length;
  try {
    if (!storage) return Math.floor(random() * total) % total;
    const stored = Number(storage.getItem(SET_STORAGE_KEY));
    return Number.isInteger(stored) && stored >= 0 && stored < total ? stored : 0;
  } catch {
    return Math.floor(random() * total) % total;
  }
}

/**
 * 다음 방문에 세울 세트를 적어둔다.
 *
 * 무작위가 아니라 순서대로 도는 이유는 두 가지다. 첫 방문자는 항상 1번 세트를 보므로
 * 첫인상을 통제할 수 있고, 다시 온 사람은 무작위와 달리 반드시 못 본 세트를 만난다.
 *
 * 같은 값으로 두 번 불러도 결과가 같다 — 지금 본 번호에서 계산하지, 저장된 값을 증가시키지 않는다.
 */
export function advanceTeaseSet(
  currentIndex: number,
  storage: Storage | null = typeof localStorage === 'undefined' ? null : localStorage,
): void {
  try {
    storage?.setItem(SET_STORAGE_KEY, String((currentIndex + 1) % LANDING_TEASE_SETS.length));
  } catch {
    // 저장이 막혀 있으면 이번 방문은 그냥 넘어간다 — 다음 방문은 무작위로 떨어진다.
  }
}

    summary_match = re.search(r'\*\*한줄 요약(?:\(공유/OG용\))?:\*\*\s*(.+)', block)
    identity_match = re.search(r'\*\*Identity(?:\s*\(기본 성향\))?:\*\*\s*(.+)', block)
    strength_match = re.search(r'\*\*Strength(?:\s*\(업무 강점\))?:\*\*\s*(.+)', block)
    blind_spot_match = re.search(r'\*\*Blind Spot(?:\s*\(주의할 점\))?:\*\*\s*(.+)', block)
    best_env_match = re.search(r'\*\*Best Environment(?:\s*\(잘 맞는 환경\))?:\*\*\s*(.+)', block)
    
    missing = []
    if not core_type_match: missing.append("core_type")
    if not summary_match: missing.append("summary")
    if not identity_match: missing.append("identity")
    if not strength_match: missing.append("strength")
    if not blind_spot_match: missing.append("blind_spot")
    if not best_env_match: missing.append("best_env")
    
    if missing:
        print(f"Block ({hangul_name.encode('utf-8')}) missing: {missing}")
        continue
        
    characters.append({
        "id": hanja_id,
        "name": f"{emoji} {char_name}",
        "emoji": emoji,
        "title": char_name,
        "core_type": core_type_match.group(1).strip(),
        "keywords": [k.strip() for k in core_type_match.group(2).split(',')],
        "summary_og": summary_match.group(1).strip(),
        "identity": identity_match.group(1).strip(),
        "strength": strength_match.group(1).strip(),
        "blind_spot": blind_spot_match.group(1).strip(),
        "best_environment": best_env_match.group(1).strip()
    })

